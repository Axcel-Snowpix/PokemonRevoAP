
PBR_SAVE_DATA_PTR = 0x8045DE80
PBR_SAVE_SLOT_SIZE: int = 0x6FF00
PBR_SAVE_SLOT_CURRENT_OFFSET = 0x50
PBR_SAVE_SLOTS_START_OFFSET = 0x380
PBR_SAVE_SLOT_CUSTOM_BATTLE_PASSES_OFFSET = 0x134D8
PBR_SAVE_SLOT_MAX_CUSTOM_BATTLE_PASSES = 34 # note, there are 3 unused passes?
PBR_SAVE_SLOT_FLAGS_OFFSET = 0x124D8
PVR_SAVE_SLOT_NUM_FLAGS = 0x28D
PBR_SAVE_SLOT_FLAG_BYTE_TOTAL = 0xE6
PBR_SAVE_SLOT_FLAG_BIT_TOTAL = 0x0000072F

class PBRSave():
    start_addr: int = 0
    save_slot_idx: int = -1
    new_flag_values = None
    old_flag_values = None

    def __init__(self):
        self.start_addr: int = 0
        self.save_slot_idx = 0
        self.flag_values = None

    def set_save_slot(self, slot: int) -> None:
        self.save_slot_idx = slot

    def set_addr(self, addr: int)  -> None:
        self.start_addr = addr

    def get_save_slot_start_addr(self) -> int:
        if (self.save_slot_idx < 0 or self.start_addr == 0):
            return 0x0 # null
        return self.start_addr + PBR_SAVE_SLOTS_START_OFFSET + (PBR_SAVE_SLOT_SIZE * self.save_slot_idx)

    def get_save_slot_flags_start_addr(self) -> int:
        if (self.save_slot_idx < 0 or self.start_addr == 0):
            return 0x0 # null
        return self.get_save_slot_start_addr() + PBR_SAVE_SLOT_FLAGS_OFFSET

    def parse_save_slot_flags_from_bytes(self, bytes) -> None:
        if (self.save_slot_idx < 0 or self.start_addr == 0):
            return
        self.old_flag_values = self.new_flag_values
        self.new_flag_values = [] #{}
        # Shift to the right by one since bit 0x72F is unused.
        all_flags = int.from_bytes(bytes, byteorder="big") >> 1
        for flag, offset_data in PBR_SAVE_SLOT_FLAG_TABLE.items():
            shift_offset = PBR_SAVE_SLOT_FLAG_BIT_TOTAL - offset_data[0] - offset_data[1]
            bitmask = ((1 << offset_data[1]) - 1) << shift_offset
            flag_value = (all_flags & bitmask) >> shift_offset
            self.new_flag_values.append(flag_value)

    def get_save_slot_flag_changes(self) -> list[tuple]:
        changes = [] #{}
        if self.new_flag_values == None or self.old_flag_values == None:
            return changes
        for flag, offset_data in PBR_SAVE_SLOT_FLAG_TABLE.items():
            if self.new_flag_values[flag] != self.old_flag_values[flag]:
                changes.append((flag, self.old_flag_values[flag], self.new_flag_values[flag]))
        return changes
        


